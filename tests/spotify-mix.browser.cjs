const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require(process.env.RCRD_PLAYWRIGHT_MODULE||'playwright');
const {createFixture,ORIGIN,tracks}=require('../walkthrough/source/demo-fixture.cjs');
(async()=>{
  const fixture=createFixture(path.resolve(__dirname,'..'),{fontManifest:{}});
  const lead={id:'A'.repeat(22),name:'The Paper Lanterns'};
  const seed={...tracks[0],artists:[lead]};
  const candidates=Array.from({length:120},(_,i)=>({...tracks[10],uri:`spotify:track:${String(900+i).padStart(22,'0')}`,name:`Related song ${i+1}`,artists:[{id:String(2000+Math.floor(i/10)).padStart(22,'0'),name:`Linked artist ${Math.floor(i/10)}`}],album:{...tracks[10].album,id:String(800+i).padStart(22,'0')}}));
  const discoveryArtists=[...new Map(candidates.map(track=>[track.artists[0].id,{id:track.artists[0].id,source:Number(track.artists[0].id)%2?'discogs-style':'listenbrainz',style:'Indie Rock'}])).values()];
  let sparse=false;let queueShuffle=false;
  const browser=await chromium.launch({headless:true,...(process.env.RCRD_CHROME_PATH?{executablePath:process.env.RCRD_CHROME_PATH}:{})});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    await context.addInitScript(fixture.sdkInstaller,fixture.initial);
    const starts=[];
    await context.route('**/*',route=>{
      const request=route.request();const url=new URL(request.url());
      const json=data=>route.fulfill({contentType:'application/json',body:JSON.stringify(data)});
      if(url.origin===ORIGIN){
        if(url.pathname==='/api/spotify/currently-playing')return json({...fixture.initial,item:seed,shuffle_state:queueShuffle});
        if(url.pathname==='/api/spotify/queue')return json({current:{uri:seed.uri,title:seed.name,artist:seed.artists[0].name,album:seed.album.name},upcoming:(queueShuffle?candidates.slice(0,3).reverse():candidates.slice(0,3)).map(track=>({uri:track.uri,title:track.name,artist:track.artists[0].name,album:track.album.name}))});
        if(url.pathname==='/api/spotify/mix-sources')return json({seed,playlists:[{id:'9'.repeat(22),tracks:[seed,...candidates.slice(0,30)]}],savedTracks:[],discoveryArtists,discoveryTracks:candidates.slice(0,sparse?20:120),discoveryWarnings:sparse?['listenbrainz-unavailable']:[],playCounts:{},partial:sparse});
        if(url.pathname==='/api/spotify/recent')return json({recentlyPlayed:[]});
        if(url.pathname==='/api/spotify/liked'&&request.method()==='GET')return json({saved:false});
        if(url.pathname==='/api/spotify/playback'&&request.postDataJSON()?.action==='start')starts.push(request.postDataJSON());
        if(url.pathname==='/api/spotify/playback'&&request.postDataJSON()?.action==='shuffle'){queueShuffle=request.postDataJSON().state;return json({ok:true})}
      }
      return /^fonts\.(googleapis|gstatic)\.com$/.test(url.hostname)?route.fulfill({contentType:'text/css',body:''}):fixture.route(route);
    });
    const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(ORIGIN);
    for(const selector of ['#playerLyrics','#playerMix','#playerMixList','#playerDiscogs']){assert.equal(await page.locator(`${selector} svg[aria-hidden="true"]`).count(),1);assert.ok(await page.locator(selector).getAttribute('aria-label'))}
    assert.equal(await page.locator('#playerMixList').getAttribute('title'),'View queue');
    await page.locator('#playerMixList:visible').click();
    const activeList=page.getByRole('dialog',{name:'Up next'});await activeList.waitFor();
    assert.equal(await activeList.locator('.active-mix-track').count(),4);
    await page.getByRole('button',{name:'Close Up next'}).click();await activeList.waitFor({state:'hidden'});
    await page.locator('#playerMix:enabled').waitFor();await page.locator('#playerMix').click();
    const mixBox=await page.locator('#playerMix').boundingBox();const heartBox=await page.locator('#playerLiked').boundingBox();
    assert.ok(Math.abs(mixBox.y-heartBox.y)<3,'Mix stays on the same player row');
    const dialog=page.getByRole('dialog',{name:'RCRD Mix',exact:true});await dialog.waitFor();
    await page.locator('#spotifyMixStart:enabled').waitFor();
    assert.equal(await dialog.locator('.mix-track').count(),100);assert.equal(await dialog.locator('.mix-track input:checked').count(),25);assert.equal(starts.length,0);
    const balancedStatus=await page.locator('#spotifyMixStatus').textContent();assert.match(balancedStatus,/from your music/);assert.match(balancedStatus,/discovery suggestions/);
    await page.locator('#spotifyMixDirection').selectOption('discover');
    assert.match(await page.locator('#spotifyMixStatus').textContent(),/1 from your music, 24 discovery suggestions/);
    await page.locator('#spotifyMixDirection').selectOption('familiar');
    assert.match(await page.locator('#spotifyMixStatus').textContent(),/25 from your music, 0 discovery suggestions/);
    await page.locator('#spotifyMixDirection').selectOption('balanced');
    assert.match(await dialog.textContent(),/Related artist via ListenBrainz/);assert.match(await dialog.textContent(),/Shares Discogs style: Indie Rock/);
    assert.match(await page.locator('#spotifyMixDescription').textContent(),/Your library and imported listening history stay local/);
    assert.deepEqual(await page.locator('#spotifyMixDescription a').evaluateAll(links=>links.map(link=>link.href)),['https://musicbrainz.org/','https://listenbrainz.org/','https://www.discogs.com/']);
    const originalSecond=await dialog.locator('.mix-track strong').nth(1).textContent();
    await dialog.locator('[data-mix-swap="1"]').click();
    assert.notEqual(await dialog.locator('.mix-track strong').nth(1).textContent(),originalSecond);
    assert.equal(await dialog.locator('.mix-track input:checked').count(),25);
    await page.locator('#spotifyMixLength').selectOption('50');
    assert.equal(await dialog.locator('.mix-track input:checked').count(),50);
    await page.locator('#spotifyMixLength').selectOption('25');
    await dialog.locator('.mix-track input').nth(1).uncheck();
    assert.match(await page.locator('#spotifyMixStatus').textContent(),/24 tracks selected/);
    assert.equal(await page.locator('#spotifyMixStart').isDisabled(),false);
    for(let index=10;index<25;index++)await dialog.locator('.mix-track input').nth(index).uncheck();
    assert.match(await page.locator('#spotifyMixStatus').textContent(),/9 tracks selected/);
    assert.equal(await page.locator('#spotifyMixStart').isDisabled(),true);
    if(process.env.RCRD_MIX_SCREENSHOT)await page.screenshot({path:process.env.RCRD_MIX_SCREENSHOT});
    await page.getByRole('button',{name:'Close RCRD Mix'}).click();
    await dialog.waitFor({state:'hidden'});assert.equal(starts.length,0);
    await page.locator('#playerMix').click();await page.locator('#spotifyMixStart:enabled').waitFor();
    await page.locator('#spotifyMixStart').click();await dialog.waitFor({state:'hidden'});
    assert.equal(starts.length,1);assert.equal(starts[0].uris.length,25);assert.equal(starts[0].uris[0],seed.uri);
    await page.locator('#playerMixList:visible').click();
    await activeList.waitFor();
    await activeList.locator('#activeSpotifyMixTracks .active-mix-track').first().waitFor();
    assert.equal(await activeList.locator('#activeSpotifyMixTracks .active-mix-track').count(),4);
    assert.equal(await activeList.locator('#activeSpotifyMixTracks .active-mix-track[aria-current="true"]').count(),1);
    assert.equal(await activeList.locator('#activeSpotifyMixSelectedTracks .active-mix-track').count(),25);
    assert.equal(await activeList.locator('#activeSpotifyMixTracks strong').nth(1).textContent(),'Related song 1');
    await page.setViewportSize({width:390,height:844});
    const listBox=await activeList.boundingBox();assert.ok(listBox.x>=0&&listBox.x+listBox.width<=390,'Mix tracklist fits a narrow viewport');
    await page.getByRole('button',{name:'Close Up next'}).click();await activeList.waitFor({state:'hidden'});
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#shuffleButton').click();await page.locator('#shuffleButton[aria-pressed="true"]').waitFor();
    await page.locator('#playerMixList').click();await activeList.waitFor();
    await activeList.locator('#activeSpotifyMixTracks .active-mix-track').first().waitFor();
    assert.equal(await activeList.locator('#activeSpotifyMixTracks strong').nth(1).textContent(),'Related song 3');
    assert.equal(await activeList.locator('#activeSpotifyMixSelectedTracks .active-mix-track').count(),25);
    await page.getByRole('button',{name:'Close Up next'}).click();await activeList.waitFor({state:'hidden'});
    await page.locator('#shuffleButton').click();await page.locator('#shuffleButton[aria-pressed="false"]').waitFor();
    await page.locator('#playerMixList').click();await activeList.waitFor();
    await activeList.locator('#activeSpotifyMixTracks .active-mix-track').first().waitFor();
    assert.equal(await activeList.locator('#activeSpotifyMixTracks strong').nth(1).textContent(),'Related song 1');
    await page.getByRole('button',{name:'Close Up next'}).click();await activeList.waitFor({state:'hidden'});
    sparse=true;await page.locator('#playerMix').click();
    await page.waitForFunction(()=>document.querySelector('#spotifyMixStatus').textContent.includes('tracks selected'));
    assert.match(await page.locator('#spotifyMixStatus').textContent(),/ListenBrainz related-artist discovery was unavailable/);
    assert.equal(await page.locator('#spotifyMixStart').isDisabled(),false);assert.equal(starts.length,1);
    assert.deepEqual(errors,[]);fixture.assertClean();
    console.log('PASS related-music Mix: 25-track default, shorter selection, cancellation, confirmed playback, and sparse-source warnings');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
